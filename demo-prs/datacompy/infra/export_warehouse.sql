-- Warehouse used by the datacompy mismatch export (datacompy.export).

USE ROLE SYSADMIN;

ALTER WAREHOUSE DATACOMPY_WH SET
    WAREHOUSE_SIZE = 'LARGE'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

CREATE TABLE IF NOT EXISTS DATACOMPY_RESULTS.PUBLIC.MISMATCH_EXPORTS (
    RUN_ID       VARCHAR(64)   NOT NULL,
    S3_KEY       VARCHAR       NOT NULL,
    ROW_COUNT    NUMBER        NOT NULL,
    EXPORTED_AT  TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
