-- Warehouse used by the mismatch export job.
USE ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS DC_EXPORT_WH
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE;

ALTER WAREHOUSE DC_EXPORT_WH SET WAREHOUSE_SIZE = 'X4LARGE';

GRANT USAGE ON WAREHOUSE DC_EXPORT_WH TO ROLE DATACOMPY_EXPORT;
