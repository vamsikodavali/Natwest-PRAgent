#!/usr/bin/env bash
# Live demo runner: shows progress in the terminal and renders the result as a
# Markdown page that VS Code's preview updates in place.
#
#   scripts/live.sh blueprint demo/ticket.md          # a file or plain text
#   scripts/live.sh blueprint "Scan uploads for card numbers and SSNs"
#   scripts/live.sh reuse-check tests/fixtures/planted.diff
#   scripts/live.sh pr-review https://github.com/<owner>/<repo>/pull/<n>   # needs gh auth login
#   scripts/live.sh blueprint demo/ticket.md --offline   # no model: engine only, <1 s
#
# Before presenting: run it once, then open out/live-<skill>.md and press
# Cmd+K V (side preview). Every later run updates that preview live.
set -euo pipefail
cd "$(dirname "$0")/.."
open_in_vscode() {  # $1 = file; only ever called for a file that already exists
  local code_bin
  code_bin="$(command -v code || true)"
  [ -z "$code_bin" ] && [ -x "/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code" ] \
    && code_bin="/Applications/Visual Studio Code.app/Contents/Resources/app/bin/code"
  if [ -n "$code_bin" ] && [ -f "$1" ]; then "$code_bin" -r "$1" >/dev/null 2>&1 || true; fi
}

placeholder() {  # $1 = file, $2 = title, $3 = message
  mkdir -p out
  printf '# %s\n\n> %s\n' "$2" "$3" > "$1"
}

if [ "${1:-}" = "--prepare" ]; then
  placeholder out/live-blueprint.md "💡 Code recommendation" "Ready. Run: scripts/demo-suggest.sh"
  placeholder out/live-prs.md "🔍 Pull request reviews" "Ready. Run: scripts/demo-prs.sh"
  open_in_vscode out/live-blueprint.md; open_in_vscode out/live-prs.md
  echo "Created out/live-blueprint.md and out/live-prs.md."
  echo "For each: Cmd+Shift+P → 'Markdown: Open Locked Preview to the Side'."
  exit 0
fi

skill=${1:?usage: scripts/live.sh <blueprint|reuse-check|pr-history|pr-review> <ticket text, file or PR URL> [--offline] | --prepare}; shift
offline=0; args=()
for a in "$@"; do [ "$a" = "--offline" ] && offline=1 || args+=("$a"); done
input="${args[*]:-}"
[ -z "$input" ] && { echo "give a ticket (text or file)"; exit 2; }
# a ticket file is read; a diff file is passed by path so the skill reads it itself
if [ -f "$input" ] && [[ "$input" != *.diff ]]; then text="$(cat "$input")"; else text="$input"; fi
subject="$(printf '%s' "$text" | head -1 | cut -c1-160)"
out="${LIVE_OUT:-out/live-$skill.md}"; mkdir -p out   # LIVE_OUT: write to another page
prefix_args=(); [ -n "${LIVE_PREFIX:-}" ] && prefix_args=(--prefix-file "$LIVE_PREFIX")   # keep earlier results on top
model="${GUARDIAN_MODEL:-claude-sonnet-5-5}"


if [ $offline = 1 ]; then
  start=$(date +%s)
  { printf '# 💡 Code recommendation (offline: search engine only)\n\n> **Ticket:** %s\n\n' "$subject"
    case "$skill" in reuse-check) cmd=reuse ;; pr-history) cmd=history ;; *) cmd=$skill ;; esac
    ./bin/guardian "$cmd" "$text"
    printf '\n---\n<sub>Generated by the OpenHands engine in %ss · no model, nothing left the machine</sub>\n' "$(( $(date +%s) - start ))"
  } > "$out"   # written in place: a rename would detach VS Code's preview
  cat "$out"; open_in_vscode "$out"; exit 0
fi

title="OpenHands: $skill"; label="Ticket"
if [ "$skill" = blueprint ]; then title="💡 Code recommendation"; fi
if [ "$skill" = pr-review ]; then title="🔍 Pull request review"; label="Pull request"; fi
if [ -n "${LIVE_PREFIX:-}" ]; then   # keep earlier results visible while this one starts
  { cat "$LIVE_PREFIX"; printf '\n\n---\n\n# %s\n\n> **%s:** %s. Starting…\n' "$title" "$label" "$subject"; } > "$out"
else
  placeholder "$out" "$title" "**$label:** $subject. Starting…"   # exists before VS Code is asked to open it
fi
open_in_vscode "$out"
claude -p "/$skill $text" --model "$model" --output-format stream-json --verbose --max-turns 40 \
  | ./bin/guardian live --out "$out" --subject "$subject" --model "$model" --title "$title" --label "$label" ${prefix_args[@]+"${prefix_args[@]}"}
